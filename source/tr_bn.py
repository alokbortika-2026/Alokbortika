def dept_bn(s):
    """'Chair · Head, Medicine' -> 'সভাপতি · বিভাগীয় প্রধান, মেডিসিন'"""
    out = []
    for part in s.split(' · '):
        if part == 'Chair': out.append('সভাপতি'); continue
        pre = ''
        for k, v in (('Head, ', 'বিভাগীয় প্রধান, '), ('Professor, ', 'অধ্যাপক, ')):
            if part.startswith(k): pre, part = v, part[len(k):]
        out.append(pre + DEPT.get(part, part))
    return ' · '.join(out)

